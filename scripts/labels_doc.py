"""List every map label for review -> docs/labels.md, from web/public/data/meta.json (run after voxelize.py).

usage: PYTHONPATH=scripts uv run python scripts/labels_doc.py
"""
import json

from aoi import ROOT, WEB_DATA

GROUPS = [(9000, "Required (seen from anywhere)"), (2500, "Extended, well known (up to 2500 m)"),
          (1300, "Extended (up to 1300 m)"), (600, "Extended, local (up to 600 m)")]
INTRO = ("Every label on the full-area map, generated by `scripts/labels.py` from the OSM features tagged with a Wikidata "
         "id (`scripts/fetch_wikidata.py`), and listed here by `scripts/labels_doc.py`. Labels show the Spanish name (the "
         "OSM name) with the English one under it where it differs. The required set is fixed in `REQUIRED`; the "
         "extended set follows the rules in `labels.py`: places (not boundaries, routes, streets, shops, people, events "
         "or organisations) whose Wikidata item has a heritage designation or a Wikipedia article, shown up to a distance "
         "that depends on how many Wikipedia editions the item has. To drop a label, add its Wikidata id to "
         "`EXTENDED_EXCLUDE` in `scripts/labels.py` (and log it in `DECISIONS.md`).")


def main():
    labels = json.loads((WEB_DATA / "meta.json").read_text())["labels"]
    out = ["# Map labels", "", INTRO]
    for far, title in GROUPS:
        rows = sorted((l for l in labels if l.get("far") == far), key=lambda l: l["name"].casefold())
        out += ["", f"## {title}: {len(rows)}", "", "| Name | English name | Kind | Wikidata |", "| --- | --- | --- | --- |"]
        out += [f"| {l['name']} | {l.get('en', '')} | {l.get('kind', '')} | {l.get('qid', '')} |" for l in rows]
    (ROOT / "docs" / "labels.md").write_text("\n".join(out) + "\n")
    print(f"{len(labels)} labels -> docs/labels.md")


if __name__ == "__main__":
    main()
